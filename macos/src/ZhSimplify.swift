    /// 是否含繁体字（用于判断要不要转换）
    static func hasTraditional(_ s: String) -> Bool {
        for ch in s where table[ch] != nil { return true }
        return false
    }

    /// 繁体转简体（逐字替换，非繁体字原样保留）
    static func simplify(_ s: String) -> String {
        // 快速路径：没有繁体字直接返回，避免逐字遍历开销
        guard hasTraditional(s) else { return s }
        var out = String()
        out.reserveCapacity(s.count)
        for ch in s {
            if let simple = table[ch] { out.append(simple) } else { out.append(ch) }
        }
        return out
    }
